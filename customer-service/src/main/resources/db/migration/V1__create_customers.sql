CREATE TABLE customers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(150) NOT NULL,
    name_normalized VARCHAR(150) GENERATED ALWAYS AS (lower(btrim(name))) STORED,
    cpf VARCHAR(11) NOT NULL,
    email VARCHAR(254) NOT NULL,
    status VARCHAR(8) NOT NULL DEFAULT 'ACTIVE',
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    deleted_at TIMESTAMP WITH TIME ZONE,
    CONSTRAINT uk_customers_cpf UNIQUE (cpf),
    CONSTRAINT ck_customers_name_not_blank CHECK (btrim(name) <> ''),
    CONSTRAINT ck_customers_cpf_format CHECK (cpf ~ '^[0-9]{11}$'),
    CONSTRAINT ck_customers_email_not_blank CHECK (btrim(email) <> ''),
    CONSTRAINT ck_customers_status CHECK (status IN ('ACTIVE', 'INACTIVE')),
    CONSTRAINT ck_customers_timestamps CHECK (updated_at >= created_at)
);
